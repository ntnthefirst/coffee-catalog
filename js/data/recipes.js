const F   = (ml) => ({ t: "foam", ml });              // milk foam
const CF  = (ml) => ({ t: "coldfoam", ml });          // cold milk foam
const W   = (ml) => ({ t: "water", ml });             // water
const I   = (g)  => ({ t: "ice", g });                // ice
